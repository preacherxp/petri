// Per-event damage flags: reread, fat, retry, thrash, and the damage they carry.
import assert from 'node:assert/strict';
import { describe, it } from 'bun:test';
import { DMG } from '../src/classify.ts';
import { dmg, first, flags, knownGap, Transcript } from './helpers.ts';

const reads = (...steps: [string, Record<string, unknown>][]) => {
  const t = new Transcript().prompt('q');
  for (const [name, inp] of steps) t.call(name, inp);
  return t.run();
};
const A = { file_path: '/w/a' };

describe('reread', () => {
  it('the second read is a reread', () => {
    const r = reads(['Read', A], ['Read', A]);
    assert.deepEqual(flags(r), [[], ['reread']]);
    assert.deepEqual(dmg(r), [0, DMG.reread]);
  });
  it('every repeat counts', () => assert.equal(reads(...Array(4).fill(['Read', A])).stats.rereads, 3));
  it('an edit invalidates', () => {
    for (const tool of ['Edit', 'Write', 'MultiEdit']) assert.equal(reads(['Read', A], [tool, A], ['Read', A]).stats.rereads, 0, tool);
  });
  it('re-reading after an edit, then again', () => {
    const r = reads(['Read', A], ['Edit', A], ['Read', A], ['Read', A]);
    assert.deepEqual(flags(r).at(-1), ['reread']);
    assert.equal(r.stats.rereads, 1);
  });
  it('editing another file does not invalidate', () => assert.equal(reads(['Read', A], ['Edit', { file_path: '/w/b' }], ['Read', A]).stats.rereads, 1));
  it('different ranges are different reads', () => {
    const r = reads(['Read', { file_path: '/w/a', offset: 1, limit: 50 }], ['Read', { file_path: '/w/a', offset: 51, limit: 50 }], ['Read', A]);
    assert.equal(r.stats.rereads, 0);
  });
  it('the same range twice is a reread', () => {
    const range = { file_path: '/w/a', offset: 1, limit: 50 };
    assert.equal(reads(['Read', range], ['Read', range]).stats.rereads, 1);
  });
  it('parallel duplicate reads', () => {
    const t = new Transcript().prompt('q');
    t.calls([['Read', A], ['Read', A]]);
    assert.equal(t.run().stats.rereads, 1);
  });
  it('a shell write invalidates', knownGap('assumption A3: every real reread was a screenshot regenerated by a shell command', () => {
    const shot = { file_path: '/w/shot.png' };
    assert.equal(reads(['Read', shot], ['Bash', { command: 'node shot.mjs > /w/shot.png' }], ['Read', shot]).stats.rereads, 0);
  }));
});

describe('fat', () => {
  const one = (size: number, err = false) => {
    const t = new Transcript().prompt('q');
    t.call('Bash', { command: 'cat big' }, 'x'.repeat(size), err);
    return first(t.run());
  };
  it('boundaries', () => {
    for (const [size, want] of [[10_000, 0], [10_001, 1], [20_000, 1], [20_001, 2], [90_000, 8], [500_000, 8]] as const) {
      const e = one(size);
      assert.equal(e.d ?? 0, want, `size ${size}`);
      assert.equal((e.flags ?? []).includes('fat'), want > 0, `size ${size}`);
    }
  });
  it('block results are summed', () => {
    const t = new Transcript().prompt('q');
    t.call('Read', A, [{ type: 'text', text: 'x'.repeat(6000) }, { type: 'text', text: 'y'.repeat(6000) }]);
    assert.ok(first(t.run()).flags!.includes('fat'));
  });
  it('fat and error stack', () => assert.equal(one(25_000, true).d, 2 + DMG.error));
});

describe('retry', () => {
  it('a verbatim retry after an error', () => {
    const t = new Transcript().prompt('q');
    t.call('Bash', { command: 'npm test' }, 'Exit code 1', true);
    t.call('Bash', { command: 'npm test' });
    const r = t.run();
    assert.deepEqual(flags(r), [[], ['retry']]);
    assert.deepEqual(dmg(r), [DMG.error, DMG.retry]);
  });
  it('changed input is not a retry', () => {
    const t = new Transcript().prompt('q');
    t.call('Bash', { command: 'npm test' }, 'x', true);
    t.call('Bash', { command: 'npm test -- --verbose' });
    assert.equal(t.run().stats.retries, 0);
  });
  it('a repeat after success is not a retry', () => {
    const t = new Transcript().prompt('q');
    t.call('Bash', { command: 'npm test' });
    t.call('Bash', { command: 'npm test' });
    assert.equal(t.run().stats.retries, 0);
  });
  it('only the immediately previous turn counts', () => {
    const t = new Transcript().prompt('q');
    t.call('Bash', { command: 'npm test' }, 'x', true);
    t.call('Read', { file_path: '/w/log' });
    t.call('Bash', { command: 'npm test' });
    assert.equal(t.run().stats.retries, 0);
  });
  it('a retry inside a parallel turn, with keys in another order', () => {
    const t = new Transcript().prompt('q');
    t.call('Grep', { pattern: 'x', path: '/nope' }, 'x', true);
    t.calls([['Grep', { path: '/nope', pattern: 'x' }], ['Read', A]]);
    assert.deepEqual(flags(t.run()), [[], ['retry'], []]);
  });
  it('same input to a different tool', () => {
    const t = new Transcript().prompt('q');
    t.call('Glob', { pattern: '*.py' }, 'x', true);
    t.call('Grep', { pattern: '*.py' });
    assert.equal(t.run().stats.retries, 0);
  });
});

describe('thrash', () => {
  const seq = (pattern: number[]) => {
    const t = new Transcript().prompt('q');
    pattern.forEach((bad, i) => t.call('Bash', { command: `try ${i}` }, bad ? 'Exit code 1' : 'ok', !!bad));
    return t.run();
  };
  it('three in a row', () => {
    const r = seq([1, 1, 1]);
    assert.equal(r.stats.thrash, 1);
    assert.deepEqual(flags(r)[2], ['thrash']);
    assert.deepEqual(dmg(r), [3, 3, 3 + DMG.thrash]);
  });
  it('counts streaks, not errors', () => assert.equal(seq(Array(6).fill(1)).stats.thrash, 1));
  it('a success resets the streak', () => {
    assert.equal(seq([1, 1, 0, 1, 1]).stats.thrash, 0);
    assert.equal(seq([1, 1, 1, 0, 1, 1, 1]).stats.thrash, 2);
  });
  it('parallel errors count in result order', () => {
    const t = new Transcript().prompt('q');
    t.calls([['Bash', { command: 'a' }, 'x', true], ['Bash', { command: 'b' }, 'x', true], ['Bash', { command: 'c' }, 'x', true]]);
    assert.equal(t.run().stats.thrash, 1);
  });
  it('unanswered calls do not break a streak', () => {
    const t = new Transcript().prompt('q');
    t.call('Bash', { command: 'a' }, 'x', true);
    t.call('Bash', { command: 'b' }, 'x', true);
    t.call('Bash', { command: 'slow' }, 'ok', false, { results: false });
    t.call('Bash', { command: 'c' }, 'x', true);
    assert.equal(t.run().stats.thrash, 1);
  });
});
